def split_header_payload(raw: bytes) -> tuple[str, bytes]:
    candidates = [(raw.find(b"\n\n"), 2), (raw.find(b"\r\n\r\n"), 4)]
    candidates = [(idx, length) for idx, length in candidates if idx >= 0]
    if not candidates:
        raise ValueError("No NRRD header terminator found")
    idx, length = min(candidates, key=lambda item: item[0])
    return raw[:idx].decode("ascii", errors="replace"), raw[idx + length :]


def parse_header(header: str) -> tuple[dict[str, str], dict[int, dict[str, str]]]:
    meta: dict[str, str] = {}
    segments: dict[int, dict[str, str]] = {}
    for line in header.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("NRRD"):
            continue
        if ":=" in line:
            key, value = line.split(":=", 1)
            meta[key] = value
        elif ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip().lower()] = value.strip()

    for key, value in meta.items():
        if not key.startswith("Segment") or "_" not in key:
            continue
        left, field = key.split("_", 1)
        try:
            idx = int(left.replace("Segment", ""))
        except ValueError:
            continue
        segments.setdefault(idx, {})[field] = value
    return meta, segments


def read_nrrd(path: Path) -> tuple[np.ndarray, dict[str, str], dict[int, dict[str, str]]]:
    header, payload = split_header_payload(path.read_bytes())
    meta, segments = parse_header(header)

    encoding = meta.get("encoding", "raw").lower()
    if encoding in ("gzip", "gz"):
        payload = gzip.decompress(payload)
    elif encoding in ("zlib", "deflate"):
        payload = zlib.decompress(payload)
    elif encoding in ("bzip2", "bz2"):
        payload = bz2.decompress(payload)
    elif encoding not in ("raw", "txt", "text", "ascii"):
        raise ValueError(f"Unsupported NRRD encoding {encoding!r} in {path}")

    dtype = np.dtype(TYPE_MAP[meta["type"].lower()])
    endian = meta.get("endian", "little").lower()
    if dtype.itemsize > 1:
        dtype = dtype.newbyteorder(">" if endian == "big" else "<")
    sizes = tuple(int(part) for part in meta["sizes"].split())

    if encoding in ("txt", "text", "ascii"):
        arr = np.fromstring(payload.decode("ascii"), sep=" ", dtype=dtype)
    else:
        arr = np.frombuffer(payload, dtype=dtype)

    expected = int(np.prod(sizes))
    if arr.size != expected:
        raise ValueError(f"{path}: expected {expected} voxels, got {arr.size}")
    return arr.reshape(sizes, order="F"), meta, segments


def storage_mask_for_segment_nuc(mask_xyz: np.ndarray) -> np.ndarray:
    """Keep Slicer XYZ storage; segment_nuc.py converts it to ZYX when loading."""
    return np.asarray(mask_xyz)


def write_binary_nrrd(
    path: Path,
    mask: np.ndarray,
    source_meta: dict[str, str],
    segment_name: str = "Cells",
) -> None:
    sizes = " ".join(str(dim) for dim in mask.shape)
    lines = [
        "NRRD0004",
        "type: unsigned char",
        "dimension: 3",
    ]

    for key in ("space", "space directions", "kinds", "space origin"):
        if key in source_meta:
            lines.append(f"{key}: {source_meta[key]}")

    lines.extend(
        [
            f"sizes: {sizes}",
            "encoding: gzip",
            "Segment0_Color:=0.8 0.2 0.2",
            "Segment0_ColorAutoGenerated:=0",
            "Segment0_LabelValue:=1",
            "Segment0_Layer:=0",
            f"Segment0_Name:={segment_name}",
            "Segment0_NameAutoGenerated:=0",
            "Segmentation_ContainedRepresentationNames:=Binary labelmap|",
        ]
    )
    header = "\n".join(lines).encode("ascii") + b"\n\n"
    payload = gzip.compress(np.asfortranarray(mask.astype(np.uint8)).tobytes(order="F"))
    path.write_bytes(header + payload)


def sample_id_from_label(path: Path) -> str:
    name = path.name
    if name.endswith("_label.seg.nrrd"):
        return name[: -len("_label.seg.nrrd")]
    if name.endswith(".seg.nrrd"):
        return name[: -len(".seg.nrrd")]
    raise ValueError(f"Unexpected label filename: {path.name}")


def find_image_for_label(label_path: Path, sample_id: str) -> Path | None:
    candidates = [
        label_path.with_name(f"{sample_id}_img.tif"),
        label_path.with_name(f"{sample_id}.tif"),
    ]
    # Some added labels keep "_label" in the NRRD name but not in the TIFF name.
    if sample_id.endswith("_label"):
        candidates.extend(
            [
                label_path.with_name(f"{sample_id[:-6]}_img.tif"),
                label_path.with_name(f"{sample_id[:-6]}.tif"),
            ]
        )
    # Some added labels omit the crop suffix in the NRRD name.
    if label_path.name == "tomo_reco_id0004_t0027.seg.nrrd":
        candidates.append(label_path.with_name("tomo_reco_id0004_t0027-1midv.tif"))
    if label_path.name == "tomo_reco_id0016_t0003.seg.nrrd":
        candidates.append(label_path.with_name("tomo_reco_id0016_t0003-1coarsev.tif"))

    for candidate in candidates:
        if candidate.exists():
            return candidate
    return None


def cell_label_from_segments(segments: dict[int, dict[str, str]]) -> int | None:
    for segment in segments.values():
        name = segment.get("Name", "").strip().lower()
        label_value = segment.get("LabelValue")
        if label_value is None:
            continue
        if name in {"cell", "cells"}:
            return int(label_value)
    return None


def planned_split_count(total: int) -> tuple[int, int, int]:
    train = round(total * SPLIT_FRACTIONS["Trainingsdaten"])
    val = round(total * SPLIT_FRACTIONS["Valdaten"])
    test = total - train - val
    if test < 1 and total >= 3:
        test = 1
        train = total - val - test
    return train, val, test


def main() -> None:
    samples = []
    skipped = []

    for root in SOURCE_ROOTS:
        for label_path in sorted(root.rglob("*.seg.nrrd")):
            mask, meta, segments = read_nrrd(label_path)
            cell_label = cell_label_from_segments(segments)
            sample_id = sample_id_from_label(label_path)
            image_path = find_image_for_label(label_path, sample_id)

            if cell_label is None:
                skipped.append((label_path, "no explicit cell/cells segment"))
                continue
            if image_path is None:
                skipped.append((label_path, "missing matching TIFF"))
                continue

            remapped = (mask == cell_label).astype(np.uint8)
            foreground_voxels = int(remapped.sum())
            if foreground_voxels == 0:
                skipped.append((label_path, f"cell label {cell_label} has no voxels"))
                continue

            source_tag = root.name
            out_sample_id = sample_id
            if any(s["sample_id"] == out_sample_id for s in samples):
                out_sample_id = f"{source_tag}_{sample_id}"

            samples.append(
                {
                    "sample_id": out_sample_id,
                    "image_path": image_path,
                    "label_path": label_path,
                    "mask": storage_mask_for_segment_nuc(remapped),
                    "meta": meta,
                    "source": source_tag,
                    "cell_label": cell_label,
                    "foreground_voxels": foreground_voxels,
                }
            )

    rng = random.Random(SEED)
    rng.shuffle(samples)
    train_count, val_count, test_count = planned_split_count(len(samples))
    split_plan = [
        ("Trainingsdaten", samples[:train_count]),
        ("Valdaten", samples[train_count : train_count + val_count]),
        ("Testdaten", samples[train_count + val_count : train_count + val_count + test_count]),
    ]

    if OUT_ROOT.exists():
        shutil.rmtree(OUT_ROOT)
    for split_name, split_samples in split_plan:
        split_dir = OUT_ROOT / split_name
        split_dir.mkdir(parents=True, exist_ok=True)
        for sample in split_samples:
            out_id = sample["sample_id"]
            shutil.copy2(sample["image_path"], split_dir / f"{out_id}_img.tif")
            write_binary_nrrd(split_dir / f"{out_id}_label.seg.nrrd", sample["mask"], sample["meta"])

    print(f"OUT_ROOT={OUT_ROOT.resolve()}")
    print(f"SEED={SEED}")
    print(f"TOTAL_INCLUDED={len(samples)}")
    for split_name, split_samples in split_plan:
        print(f"{split_name}={len(split_samples)}")
        for sample in split_samples:
            print(
                f"  {sample['sample_id']}\t"
                f"source={sample['source']}\t"
                f"cell_label={sample['cell_label']}\t"
                f"fg_voxels={sample['foreground_voxels']}"
            )

    print(f"SKIPPED={len(skipped)}")
    for path, reason in skipped:
        print(f"  {path}\t{reason}")


if __name__ == "__main__":
    main()
